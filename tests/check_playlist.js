const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const window={}, storage=new Map();
const local={getItem:key=>storage.get(key),setItem:(key,value)=>storage.set(key,value)};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../desktop/ui/playlist.js'),'utf8'),
  {window,crypto:require('node:crypto').webcrypto});
const list=new window.Playlist(local);
list.add(17,'default');list.add(17,'custom-a');list.add(51,null);list.add(17,'default');
const [a,b,c,d]=list.items;
assert.notEqual(a.id,d.id);
list.start(a.id,true);assert.equal(list.next(1,true),b);
list.start(d.id,false);assert.equal(list.next(1,true),null);
list.setMode('loopList');assert.equal(list.next(1,true),a);
list.setMode('repeatOne');list.start(c.id,true);
assert.equal(list.next(1,true),c);assert.equal(list.next(1),d);
assert.equal(list.engineMode(),'repeatOne');
list.keep(entry=>entry!==c);
assert.equal(list.engineMode(),'ordered');assert.equal(list.next(1,true),d);
list.keep(entry=>entry!==a);assert.equal(list.next(-1),b);
list.move(d.id,-1);
const restored=new window.Playlist(local);
assert.deepEqual(restored.items.map(i=>i.id),list.items.map(i=>i.id));
assert.equal(restored.items[0].id,d.id);assert.equal(restored.items[1].planId,'custom-a');
assert.equal(restored.mode,'repeatOne');assert.equal(restored.active,false);
restored.add(21,null);restored.setMode('shuffle');restored.start(d.id,true);
const round=new Set([d.id]);
for (let i=1;i<restored.items.length;i++) {
  const next=restored.next(1,true);assert(!round.has(next.id));
  round.add(next.id);restored.start(next.id,false);
}
assert.notEqual(restored.next(1,true).id,restored.current);
restored.keep(()=>false);assert.equal(restored.next(1),null);
const nav=new window.Playlist.TrackNavigation();
const tracks=[a,b,c,d];
let draws=0;
const draw=()=>tracks[++draws%tracks.length];
let view=nav.neighbors(tracks,a.id,'shuffle',draw);
assert.equal(view.previous,null);assert.equal(view.following,b);
assert.equal(nav.neighbors(tracks,a.id,'shuffle',draw),view);assert.equal(draws,1);
nav.moved(1);
view=nav.neighbors(tracks,b.id,'shuffle',draw);
assert.equal(view.previous,a);assert.equal(view.following,c);
nav.moved(-1);
view=nav.neighbors(tracks,a.id,'shuffle',draw);
assert.equal(view.following,b);assert.equal(draws,2);
view=nav.neighbors([a,c,d],a.id,'shuffle',draw);
assert.equal(view.following,d);assert.equal(view.previous,null);
view=nav.neighbors(tracks,b.id,'ordered',delta=>tracks[1+delta]);
assert.equal(view.previous,a);assert.equal(view.following,c);
console.log('Passed playlist modes, removal, stable track previews and shuffle history.');
